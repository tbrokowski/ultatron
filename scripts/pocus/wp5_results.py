#!/usr/bin/env python3
"""
wp5_results.py  ·  Paste-ready text for every WP5 field (spec §8)
=================================================================

Reads analysis.json + data_facts.json + env captures and writes WP5_results.md
in the WP1 wording style.  Numbers are taken from analysis.json only.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def _fmt(x: Any, nd: int = 3) -> str:
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def render(analysis: dict, data_facts: dict | None = None) -> str:
    lines = [
        "# WP5 results (POCUS) — paste-ready",
        "",
        "Generated by `scripts/pocus/wp5_results.py`. Every number is copied",
        "from `analysis.json` (spec §9: analysis.json reproduces WP5_results.md).",
        "",
        "## Resource table",
        "",
        "Split row 5 into 5a encoder pretraining, 5b multimodal RL, 5c teacher",
        "reference generation.  Fill n*, E(n*), run durations from §6.3–6.5.",
        "",
    ]
    series = analysis.get("series") or {}
    for name, block in series.items():
        lines += [
            f"### Series `{name}`",
            "",
            f"- n0 = {block.get('n0')}",
            f"- n* = {block.get('n_star')}  ({block.get('n_star_reason')})",
            f"- Amdahl f = {_fmt(block.get('amdahl_f'))}",
            "- Efficiency E(n): " + ", ".join(
                f"{k} GPUs → {_fmt(v)}" for k, v in (block.get("efficiency") or {}).items()
            ),
            "- Speed-up S(n): " + ", ".join(
                f"{k} GPUs → {_fmt(v)}" for k, v in (block.get("speedup") or {}).items()
            ),
            "",
        ]
    gpuh = analysis.get("gpuh") or {}
    lines += [
        "## GPUh request",
        "",
        "```json",
        json.dumps(gpuh, indent=2, default=str),
        "```",
        "",
        "## Benchmarked? / Difference to prod / Data ready",
        "",
        "- Benchmarked: yes (job IDs in `runs.csv`).",
        "- Difference: data subset (US-365K + 3 video sets vs the production corpus);",
        "  Qwen3-VL stand-in for the Apertus-based policy.",
        "- Data ready: US-365K and the video sets — see `data_facts.json`;",
        "  production corpus [status TBC].",
        "",
        "## Storage",
        "",
        "```json",
        json.dumps(analysis.get("storage") or {}, indent=2, default=str),
        "```",
        "",
        "## Datasets / licences",
        "",
    ]
    if data_facts:
        for ds, rec in (data_facts.get("datasets") or {}).items():
            lines.append(
                f"- **{ds}**: licence={rec.get('licence')}; "
                f"sensitivity={rec.get('sensitivity')}; "
                f"raw bytes={(rec.get('raw') or {}).get('bytes')}"
            )
        lines.append("")
    lines += [
        "## Application Efficiency — ultrasound encoder pretraining",
        "",
        "E0–E6: see `runs.csv` (A-stage1, A-stage2-img, A-stage2-vid),",
        "`components.csv`, GSSR folders, and the encoder env captures.",
        "Metric: images/s and clips/s at fixed GBS (2048 images / 32 clips).",
        "Minimal setup: 1 GPU then 1 node (E0). Strong scaling: 1/2/4/8 nodes.",
        "",
        "## Application Efficiency — multimodal GRPO",
        "",
        "R0–R5: see `runs.csv` (B-prod, B-handbook). Metric: E2E tokens/s and",
        "samples/s. Teacher latency is `t_teacher` in `components.csv`.",
        "",
        "## Quality monitoring",
        "",
        "R3 held-out teacher reward curve (every 10 steps). Encoder probe suite:",
        "BUSI, BUS-BRA, CAMUS, TN3K, Fetal Planes, LUS TB.",
        "",
        "## Software",
        "",
        "Pinned in each `env/<jobid>.txt`: git HEAD, container digest, pip freeze,",
        "nvidia-smi header, NCCL_*/FI_*, Slurm header, resolved YAML.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--analysis", type=Path, required=True)
    p.add_argument("--data-facts", type=Path, default=None)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    analysis = json.loads(args.analysis.read_text(encoding="utf-8"))
    facts = None
    if args.data_facts and args.data_facts.exists():
        facts = json.loads(args.data_facts.read_text(encoding="utf-8"))
    text = render(analysis, facts)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
